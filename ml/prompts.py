"""Промпты и схемы протокола совещания для локальной LLM (Hex.team).

Вход транскрипта — HEX-формат:
{"transcript": [{"speaker_id", "start_ms", "end_ms", "text"}, ...]}
Таймкоды в выходе — те же миллисекунды от начала записи (start_ms реплики-источника).

Главное правило анти-выдумки: данных нет в тексте -> null / пустой список.
"""
import json

BASE_RULES = (
    "Ты — протоколист совещания. Работаешь ТОЛЬКО с текстом транскрипта.\n"
    "Жёсткие правила:\n"
    "1. Не выдумывай факты, имена, сроки и цифры — только то, что есть в тексте.\n"
    "2. Нет данных — пиши null или пустой список [].\n"
    "3. Таймкод — start_ms реплики, где это было сказано (миллисекунды, число).\n"
    "4. Пиши на языке записи (по умолчанию русский).\n"
    "5. Ответ — СТРОГО валидный JSON, без markdown, без пояснений."
)

# ---------- Схема протокола ----------
MINUTES_SCHEMA = {
    "title": "короткое название встречи (до 8 слов)",
    "summary": "резюме в 2-4 предложениях",
    "topics": [{"name": "тема", "start_ms": 0, "key_points": ["тезис"]}],
    "decisions": [{"decision": "что решили", "start_ms": 0}],
    "action_items": [
        {
            "task": "что сделать",
            "owner": "ответственный или null",
            "deadline": "срок как сказано в записи или null",
            "start_ms": 0,
        }
    ],
    "open_questions": [{"question": "вопрос, оставшийся без ответа", "start_ms": 0}],
}

MINUTES_PROMPT = (
    BASE_RULES
    + "\n\nЗадача: составь протокол встречи по транскрипту.\n"
    "ВАЖНО про таймкоды: каждая реплика начинается с [<число> ms]. Копируй это "
    "число в start_ms без изменений. Запрещено писать 0 или null, если элемент "
    "взят из текста. Нет элемента в тексте — не добавляй его вовсе.\n"
    "Решение — только явно подтверждённое договорённостью («решили», «договорились», "
    "«делаем так»); предположение или обсуждение — НЕ решение.\n"
    "Задача (action_item) — только если кто-то явно взял обязательство или ему "
    "поручили; «надо бы» — не задача. Ответственный — только если назван или "
    "однозначно понятен из реплик, иначе null. Срок — только если прозвучал, "
    "иначе null.\n"
    "Если в тексте нет подтверждённых решений, поручений или открытых вопросов — "
    "оставь соответствующий список ПУСТЫМ ([]), не выдумывай элементы.\n"
    "Верни JSON по схеме:\n"
    + json.dumps(MINUTES_SCHEMA, ensure_ascii=False, indent=2)
)

# ---------- Длинные записи: chunk -> merge ----------
CHUNK_PROMPT = (
    BASE_RULES
    + "\n\nЭто ФРАГМЕНТ длинной записи. Составь протокол этого фрагмента по той "
    "же схеме. Таймкоды — из этого фрагмента, в миллисекундах от начала всей "
    "записи (они уже даны в репликах, просто копируй).\n"
    "Верни JSON по схеме:\n"
    + json.dumps(MINUTES_SCHEMA, ensure_ascii=False, indent=2)
)

MERGE_PROMPT = (
    BASE_RULES
    + "\n\nНиже — JSON-протоколы последовательных фрагментов одной записи. "
    "Объедини их в один итоговый протокол: убери дубли, склей повторяющиеся "
    "темы, сохрани все таймкоды, резюме напиши заново по всему содержанию, "
    "название выбери одно. Ничего не выдумывай — только то, что есть во "
    "фрагментах.\n"
    "Верни JSON по схеме:\n"
    + json.dumps(MINUTES_SCHEMA, ensure_ascii=False, indent=2)
)

# ---------- Вопросы по записи ----------
QA_SCHEMA = {
    "answer": "ответ по тексту записи; если информации нет — «В записи этого нет»",
    "start_ms": 0,
}

QA_PROMPT = (
    BASE_RULES
    + "\n\nОтветь на вопрос ТОЛЬКО по транскрипту. Формулировки в записи могут "
    "отличаться от слов вопроса — ищи по смыслу (синонимы, перефразировки). "
    "В start_ms скопируй число из [<число> ms] реплики, где есть ответ. "
    "реплики, из которой взят ответ (самой ранней по теме). Если в записи нет "
    "ответа — answer: «В записи этого нет», start_ms: null.\n"
    "Верни JSON по схеме:\n"
    + json.dumps(QA_SCHEMA, ensure_ascii=False, indent=2)
)


# ---------- Форматирование транскрипта ----------
def format_transcript(segments: list[dict]) -> str:
    """HEX-сегменты -> читаемый текст с таймкодами для промпта."""
    lines = []
    for seg in segments:
        lines.append(
            f"[{seg['start_ms']} ms] {seg['speaker_id']}: {seg['text']}"
        )
    return "\n".join(lines)


def build_minutes_prompt(segments: list[dict], chunk: bool = False) -> str:
    head = CHUNK_PROMPT if chunk else MINUTES_PROMPT
    return head + "\n\nТранскрипт:\n" + format_transcript(segments)


def build_merge_prompt(partials: list[dict]) -> str:
    body = json.dumps(partials, ensure_ascii=False, indent=2)
    return MERGE_PROMPT + "\n\nПротоколы фрагментов:\n" + body


def build_qa_prompt(segments: list[dict], question: str) -> str:
    return (
        QA_PROMPT
        + "\n\nТранскрипт:\n"
        + format_transcript(segments)
        + "\n\nВопрос: "
        + question
    )
